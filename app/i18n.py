def normalize_language(language: str | None) -> str:
    """Return a supported language code, falling back to Chinese."""

    return language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def get_language() -> str:
    return _current_language


def set_language(language: str) -> str:
    global _current_language
    _current_language = normalize_language(language)
    return _current_language


def language_display_name(language: str | None = None) -> str:
    return LANGUAGE_NAMES[normalize_language(language or _current_language)]


def tr(source: str, **values: object) -> str:
    """Translate source text using Chinese as the stable fallback key."""

    template = source if _current_language == DEFAULT_LANGUAGE else _EN_TRANSLATIONS.get(source, source)
    if not values:
        return template
    try:
        return template.format(**values)
    except (KeyError, IndexError, ValueError):
        return source.format(**values)


def load_language() -> str:
    settings = QSettings(ORGANIZATION_NAME, APP_NAME)
    language = normalize_language(str(settings.value(LANGUAGE_SETTING_KEY, DEFAULT_LANGUAGE)))
    return set_language(language)


def save_language(language: str) -> None:
    normalized = normalize_language(language)
    settings = QSettings(ORGANIZATION_NAME, APP_NAME)
    settings.setValue(LANGUAGE_SETTING_KEY, normalized)
    settings.sync()
